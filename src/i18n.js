let lang = 'es';
const listeners = new Set();

export const getLang = () => lang;
export const t = (key) => DICT[lang][key] ?? DICT.es[key] ?? key;
export const onLangChange = (fn) => listeners.add(fn);

export function initI18n() {
  // Cache the Spanish copy that ships in the HTML.
  document.querySelectorAll('[data-i18n]').forEach((el) => { DICT.es[el.dataset.i18n] ??= el.textContent; });
  document.querySelectorAll('[data-i18n-ph]').forEach((el) => { DICT.es[el.dataset.i18nPh] ??= el.placeholder; });

  let saved = null;
  try { saved = localStorage.getItem('sm-lang'); } catch { /* storage blocked */ }
  const initial = saved || (navigator.language?.toLowerCase().startsWith('es') ? 'es' : 'en');
  setLang(initial, false);

  document.querySelector('[data-lang-toggle]')?.addEventListener('click', () => setLang(lang === 'es' ? 'en' : 'es'));
}

export function setLang(next, persist = true) {
  lang = next;
  document.documentElement.lang = next;
  document.querySelectorAll('[data-i18n]').forEach((el) => { el.textContent = t(el.dataset.i18n); });
  document.querySelectorAll('[data-i18n-ph]').forEach((el) => { el.placeholder = t(el.dataset.i18nPh); });
  document.querySelectorAll('[data-lang]').forEach((el) => el.classList.toggle('is-on', el.dataset.lang === next));
  if (persist) { try { localStorage.setItem('sm-lang', next); } catch { /* storage blocked */ } }
  listeners.forEach((fn) => fn(next));
}
